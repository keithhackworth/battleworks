#!/usr/bin/env node
'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {setTimeout: sleep} = require('node:timers/promises');
const {parseArgs} = require('node:util');
const {cloudAssetId} = require('./import-glb');
const {trimPng} = require('./trim-ui-png');

const PNG_SIGNATURE = Buffer.from('89504e470d0a1a0a', 'hex');
const MAX_BYTES = 20_000_000;
const toRelativePath = value => value.split(path.sep).join('/');
const isPng = file => /\.png$/i.test(file);

function validPath(value) {
 return typeof value === 'string' && !/[\\\x00-\x1f\x7f]/.test(value) &&
  value.split('/').every(segment => segment && segment !== '.' && segment !== '..');
}

async function* listFiles(target) {
 const stat = await fs.lstat(target);
 if (stat.isDirectory()) {
  for (const child of (await fs.readdir(target)).sort()) {
   yield* listFiles(path.join(target, child));
  }
 } else if (stat.isFile() && isPng(target)) {
  yield target;
 }
}

function dimensions(bytes) {
 if (bytes.length < 45 || !bytes.subarray(0, 8).equals(PNG_SIGNATURE) ||
     bytes.readUInt32BE(8) !== 13 || bytes.toString('ascii', 12, 16) !== 'IHDR') {
  throw new Error('Invalid PNG header');
 }
 const width = bytes.readUInt32BE(16);
 const height = bytes.readUInt32BE(20);
 if (!width || !height || width >= 8000 || height >= 8000) {
  throw new Error('PNG dimensions must be between 1 and 7999 pixels per side');
 }
 let hasImageData = false;
 for (let offset = 33; offset + 12 <= bytes.length;) {
  const length = bytes.readUInt32BE(offset);
  const type = bytes.toString('ascii', offset + 4, offset + 8);
  offset += length + 12;
  if (offset > bytes.length) break;
  if (type === 'IDAT' && length > 0) hasImageData = true;
  if (type === 'IEND' && !length && offset === bytes.length && hasImageData) return {width, height};
 }
 throw new Error('Invalid or truncated PNG chunks');
}

async function loadManifest(file) {
 let manifest;
 try {
  manifest = JSON.parse(await fs.readFile(file, 'utf8'));
 } catch (error) {
  if (error.code !== 'ENOENT') throw error;
  return new Map();
 }
 if (manifest.version !== 1 || !Array.isArray(manifest.images)) throw new Error('Invalid UI asset manifest');
 const images = new Map();
 for (const item of manifest.images) {
  if (!item || !validPath(item.source) || !isPng(item.source) || images.has(item.source) ||
      typeof item.name !== 'string' || typeof item.assetId !== 'string' || !/^[1-9]\d*$/.test(item.assetId) ||
      !/^[a-f0-9]{64}$/.test(item.sha256) ||
      ![item.width, item.height].every(size => Number.isInteger(size) && size > 0 && size < 8000)) {
   throw new Error('Invalid image entry in UI asset manifest');
  }
  images.set(item.source, item);
 }
 return images;
}

function registrySource(images) {
 // JSON strings also work in Luau for these paths and names (control characters are excluded).
 const quote = value => JSON.stringify(value);
 const lines = images.map(item => (
  `\t{ source = ${quote(item.source)}, name = ${quote(item.name)}, assetId = ${quote(item.assetId)}, width = ${item.width}, height = ${item.height} },`
 ));
 return ['-- Generated by tools/import-ui.js', 'return {', ...lines, '}', ''].join('\n');
}

// Check each destination segment before writing, including when the source is external.
async function ensureDestination(assets, source, create) {
 const parts = ['ui', ...source.split('/')];
 let current = assets;
 for (const [index, part] of parts.entries()) {
  current = path.join(current, part);
  const isFile = index === parts.length - 1;
  const stat = await fs.lstat(current).catch(error => {
   if (error.code !== 'ENOENT') throw error;
  });
  if (!stat && !create) return path.join(current, ...parts.slice(index + 1));
  if (!stat && !isFile) await fs.mkdir(current);
  if (stat && !(isFile ? stat.isFile() : stat.isDirectory())) {
   throw new Error(`Unexpected destination type at ${current}`);
  }
 }
 return current;
}

async function importUI(root, target, options = {}, log = console.log, env = process.env, fetcher = fetch, wait = sleep) {
 const assets = await fs.realpath(path.join(root, 'assets'));
 const sourceRoot = path.join(assets, 'ui');
 const input = path.resolve(root, target);
 const inputStat = await fs.lstat(input);
 if (inputStat.isSymbolicLink()) throw new Error('Choose a real PNG file or directory');
 const inputReal = await fs.realpath(input);
 const inSourceRoot = inputReal === sourceRoot || inputReal.startsWith(sourceRoot + path.sep);
 const prefix = options.into;
 if (prefix !== undefined && (!validPath(prefix) || inSourceRoot)) {
  throw new Error('--into requires a relative directory and a source outside assets/ui/');
 }
 const files = [];
 for await (const file of listFiles(inputReal)) files.push(file);
 if (!files.length) throw new Error('No PNG files found');

 const manifest = path.join(assets, 'ui-manifest.json');
 const registry = path.join(root, 'src/shared/UIAssetData.luau');
 const lock = path.join(assets, '.import-ui.lock');
 const dryRun = options['dry-run'];
 if (!dryRun) {
  try {
   await fs.mkdir(lock);
  } catch (error) {
   if (error.code === 'EEXIST') throw new Error('Another UI import holds assets/.import-ui.lock');
   throw error;
  }
 }

 const failures = [];
 try {
  const images = await loadManifest(manifest);
  async function replaceFile(file, contents) {
   const pending = path.join(lock, 'pending');
   await fs.writeFile(pending, contents);
   await fs.rename(pending, file);
  }

  let changed = false;
  for (const file of files) {
   const relative = inSourceRoot ? path.relative(sourceRoot, file) :
    inputStat.isDirectory() ? path.relative(inputReal, file) : path.basename(file);
   const source = prefix ? `${prefix}/${toRelativePath(relative)}` : toRelativePath(relative);
   try {
    if (!validPath(source)) throw new Error('Invalid relative PNG path');
    const destination = await ensureDestination(assets, source, false);
    const stat = await fs.stat(file);
    if (stat.size > MAX_BYTES) throw new Error('PNG exceeds the 20 MB upload limit');
    const bytes = await fs.readFile(file);
    const originalSize = dimensions(bytes);
    const upload = options.trim ? await trimPng(bytes, originalSize, MAX_BYTES) : bytes;
    const trimmed = upload !== bytes;
    const size = trimmed ? dimensions(upload) : originalSize;
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const previous = images.get(source);
    const unchanged = !options.force && previous?.sha256 === sha256 &&
     Boolean(previous.trimmed) === trimmed && previous.width === size.width && previous.height === size.height;
    const crop = trimmed ? ` (trimmed ${originalSize.width}×${originalSize.height} to ${size.width}×${size.height})` : '';
    if (dryRun) {
     log(`${unchanged ? 'Unchanged' : 'Would upload'}: ${source}${crop}`);
     continue;
    }

    if (unchanged) {
     const stored = file === destination ? bytes : await fs.readFile(destination).catch(error => {
      if (error.code !== 'ENOENT') throw error;
     });
     if (!stored?.equals(bytes)) {
      await ensureDestination(assets, source, true);
      await replaceFile(destination, bytes);
     }
     log(`Unchanged: ${source}`);
     continue;
    }

    const name = path.basename(source, path.extname(source));
    const displayName = `BattleWorks UI ${name}`.slice(0, 50);
    const assetId = await cloudAssetId(upload, {
     assetType: 'Image', mime: 'image/png', fileName: 'image.png',
     name: displayName, description: 'BattleWorks UI image',
    }, message => log(message.split('. Resume with')[0]), env, fetcher, wait);
    if (file !== destination) {
     await ensureDestination(assets, source, true);
     await replaceFile(destination, bytes);
    }
    images.set(source, {name, source, assetId, ...size, sha256, ...(trimmed && {trimmed: true})});
    changed = true;
    log(`Imported: ${source}${crop} → ${assetId}`);
   } catch (error) {
    failures.push(`${source}: ${error.message.split('. Resume with')[0]}`);
   }
  }

  if (!dryRun) {
   const sorted = [...images.keys()].sort().map(source => images.get(source));
   if (changed) await replaceFile(manifest, JSON.stringify({version: 1, images: sorted}, null, 2) + '\n');
   const generated = registrySource(sorted);
   if (await fs.readFile(registry, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
   }) !== generated) await replaceFile(registry, generated);
  }
 } finally {
  if (!dryRun) await fs.rm(lock, {recursive: true, force: true});
 }
 if (failures.length) throw new Error(failures.join('\n'));
}

if (require.main === module) (async () => {
 const {values, positionals} = parseArgs({
  allowPositionals: true,
  options: {'dry-run': {type: 'boolean'}, force: {type: 'boolean'}, trim: {type: 'boolean'}, into: {type: 'string'}},
 });
 if (positionals.length !== 1) {
  throw new Error('Usage: node tools/import-ui.js <png-or-directory> [--into RELATIVE_DIR] [--dry-run] [--force] [--trim]');
 }
 await importUI(path.resolve(__dirname, '..'), positionals[0], values);
})().catch(error => {
 console.error(error.message);
 process.exitCode = 1;
});

module.exports = {importUI};
