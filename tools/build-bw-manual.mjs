#!/usr/bin/env node
// Export real in-game reference content, not a separately hand-written manual.
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const runtime=process.argv.slice(2).find(arg=>!arg.startsWith('--'))||'/tmp/battleworks-luau-check/node_modules/luau-web/src/index.js';
const check=process.argv.includes('--check');
const appendixFiles=['docs/BW_CORE_API_SPEC.md','docs/SCANNER_TERRAIN.md'];
const appendix='\nAPPENDIX: EXACT OWN-STATE API AND SCANNER SCHEMA\n'+(await Promise.all(appendixFiles.map(async file=>'\n===== '+file+' =====\n'+await fs.readFile(path.join(root,file),'utf8')))).join('\n');
const appendixModule='-- Generated by tools/build-bw-manual.mjs; keep API/schema appendix synchronized.\nreturn '+JSON.stringify(appendix)+'\n';
const appendixPath=path.join(root,'src/shared/BWManualAppendix.luau');
if(check){if(await fs.readFile(appendixPath,'utf8')!==appendixModule)throw new Error('Stale BW manual appendix; regenerate.');}
else await fs.writeFile(appendixPath,appendixModule);
const {LuauState}=await import(pathToFileURL(path.resolve(runtime)).href);
let exported;
const state=await LuauState.createAsync({print:(tag,value)=>{if(tag==='MANUAL_EXPORT')exported=value;}});
try{
 let bundle=await fs.readFile(path.join(root,'tests/RobloxMock.luau'),'utf8');
 bundle+='\nlocal Shared,loaders,cache,require={},{},{},nil\n';
 const files=(await fs.readdir(path.join(root,'src/shared'))).filter(file=>file.endsWith('.luau')).sort();
 for(const file of files){const name=file.replace('.luau','');bundle+='Shared['+JSON.stringify(name)+']='+JSON.stringify(name)+'\n';}
 for(const file of files){const name=file.replace('.luau','');bundle+='loaders['+JSON.stringify(name)+']=function() local script={Parent=Shared}\n'+await fs.readFile(path.join(root,'src/shared',file),'utf8')+'\nend\n';}
 bundle+='require=function(name) if cache[name]==nil then cache[name]=assert(loaders[name],name)()end return cache[name]end\nprint("MANUAL_EXPORT",require("BWHandbook").exportText())';
 await state.loadstring(bundle,'manual-export',true)();
 if(typeof exported!=='string'||exported.length<10000)throw new Error('Manual export incomplete');
 const output=path.join(root,'docs/BW_MANUAL.txt');
 if(check){if(await fs.readFile(output,'utf8')!==exported)throw new Error('Stale BW_MANUAL.txt; regenerate.');}
 else await fs.writeFile(output,exported);
 console.log(`${check?'Verified':'Generated'} ${output}: ${Buffer.byteLength(exported)} UTF-8 bytes`);
}finally{state.destroy();}
