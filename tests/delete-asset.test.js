'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const {spawnSync}=require('node:child_process');
const {deleteAsset}=require('../tools/delete-asset');
const {readHiddenAssets}=require('../tools/world-builder/hidden-assets');
const {catalog}=require('../tools/world-builder/catalog');
const {buildEditorCatalog}=require('../tools/build-editor-catalog');
const mesh=(name,id)=>`<Item class="Model" referent="${id}"><Properties><string name="Name">${name}</string></Properties><Item class="MeshPart" referent="${id}P"><Properties><string name="Name">Deck</string><Content name="MeshId"><url>rbxassetid://123456</url></Content></Properties></Item></Item>`;
test('hide previews, counts world IDs once and preserves worlds and bundled models',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'bw-delete-test-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const native=path.join(root,'assets/roblox');
 for(const dir of [native,path.join(root,'worlds'),path.join(root,'GLBs/forest')]) await fs.mkdir(dir,{recursive:true});
 const bundle=path.join(native,'assets.rbxm');
 const xml=path.join(root,'bundle.rbxmx');
 await fs.writeFile(xml,`<roblox version="4"><Item class="Folder"><Properties><string name="Name">Library</string></Properties><Item class="Folder"><Properties><string name="Name">Forest</string></Properties>${mesh('bridge','B')}${mesh('tower','T')}</Item></Item></roblox>`);
 const project=path.join(root,'fixture.project.json');
 await fs.writeFile(project,JSON.stringify({name:'Library',tree:{$path:xml}}));
 const built=spawnSync('rojo',['build',project,'-o',bundle],{encoding:'utf8'});
 assert.equal(built.status,0,built.stderr);
 const source=path.join(root,'GLBs/forest/bridge.glb');
 await fs.writeFile(source,'source fixture');
 await fs.writeFile(path.join(root,'worlds/roblox-assets.json'),'{}');
 await fs.writeFile(path.join(root,'worlds/asset-resizing.json'),'{"Forest/bridge":[true,true,true]}');
 await fs.writeFile(path.join(root,'worlds/asset-collision-generation.json'),'{"enabled":false,"sourceFolders":{"Forest":"GLBs/forest"}}');
 await buildEditorCatalog(root);
 const before=await fs.readFile(bundle);
 const messages=[];
 await deleteAsset(root,'/Forest/Bridge',{},message=>messages.push(message));
 assert.ok(messages.some(message=>message.includes('Preview only')));
 assert.deepEqual(await fs.readFile(bundle),before);
 const world=path.join(root,'worlds/placed.json');
 const compiled=path.join(root,'build/worlds/placed.builder.json');
 const unrelated=path.join(root,'worlds/unrelated.json');
 const legacy=path.join(root,'worlds/legacy.json');
 const definitions=path.join(root,'worlds/definitions.json');
 const studio=path.join(root,'worlds/studio-worlds.model.json');
 const selected=path.join(root,'worlds/selected-world.model.json');
 const published=path.join(root,'worlds/published-world.model.json');
 const write=(file,data)=>fs.writeFile(file,JSON.stringify(data));
 const value=(Name,Value)=>({Name,ClassName:'StringValue',Properties:{Value}});
 const entry=id=>({Name:id,ClassName:'Configuration',Children:[value('WorldId',id)]});
 await fs.mkdir(path.dirname(compiled),{recursive:true});
 await write(world,{schemaVersion:2,id:'placed',objects:[{asset:'Forest/bridge'}]});
 await write(compiled,{version:1,id:'placed',objects:[{asset:'Forest/bridge'}]});
 await write(unrelated,{schemaVersion:2,id:'unrelated',name:'Forest/bridge',objects:[{asset:'Forest/tower'}]});
 await write(legacy,{version:1,id:'legacy',definitionFiles:['definitions.json'],instances:[{id:'deck',ref:'deck'}]});
 await write(definitions,{definitions:{deck:{type:'model',asset:'Forest/bridge'}}});
 await write(studio,{ClassName:'Folder',Children:['placed','legacy','unrelated'].map(entry)});
 await write(selected,value('Selected','placed'));
 await write(published,value('Published','unrelated'));
 await deleteAsset(root,'Forest/bridge',{},message=>messages.push(message));
 assert.ok(messages.some(message=>message.includes('worlds using this asset: 2')));
 await assert.rejects(deleteAsset(root,'Forest/bridge',{apply:true},()=>{}),/interactive confirmation/);
 await deleteAsset(root,'Forest/bridge',{apply:true,confirm:count=>{assert.equal(count,2);return false;}},()=>{});
 assert.deepEqual(await fs.readFile(bundle),before);
 await fs.access(world);
 assert.deepEqual(await readHiddenAssets(root),[]);
 const preserved=[bundle,source,world,compiled,legacy,unrelated,definitions,studio,selected,published];
 const snapshots=await Promise.all(preserved.map(file=>fs.readFile(file)));
 await deleteAsset(root,'Forest/bridge',{apply:true,confirm:count=>{assert.equal(count,2);return true;}},()=>{});
 assert.deepEqual(await readHiddenAssets(root),['Forest/bridge']);
 assert.deepEqual(await Promise.all(preserved.map(file=>fs.readFile(file))),snapshots);
 const entries=await catalog(root);
 assert.equal(entries.find(item=>item.model==='Forest/bridge').hidden,true);
 assert.equal(entries.find(item=>item.model==='Forest/tower').hidden,undefined);
 await assert.rejects(deleteAsset(root,'Forest/typo',{apply:true},()=>{}),/No asset found/);

});

test('built-ins, standalone assets and cloud assets use the same hide list',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'bw-delete-standalone-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 for(const dir of ['assets/roblox/Forest','GLBs/forest','worlds'])await fs.mkdir(path.join(root,dir),{recursive:true});
 const local=path.join(root,'assets/roblox/Forest/local.rbxmx');
 const source=path.join(root,'GLBs/forest/shared.glb');
 await fs.writeFile(local,`<roblox version="4">${mesh('local','L')}</roblox>`);
 await fs.writeFile(source,'source fixture');
 const registry=path.join(root,'worlds/roblox-assets.json');
 await fs.writeFile(registry,JSON.stringify({
  local:{model:'Forest/local',source:'GLBs/forest/shared.glb'},
  cloud:{model:'Forest/cloud',source:'GLBs/forest/shared.glb',cloudModel:{assetId:'456',creatorId:'123',creatorType:'User'}},
 }));
 await fs.writeFile(path.join(root,'worlds/asset-collision-generation.json'),'{"enabled":false}');
 await buildEditorCatalog(root);
 await deleteAsset(root,'Forest/local',{apply:true},()=>{});
 await fs.access(local);
 await fs.access(source);
 await deleteAsset(root,'Forest/cloud',{apply:true},()=>{});
 await fs.access(source);
 const messages=[];
 await fs.writeFile(path.join(root,'worlds/pond.json'),JSON.stringify({schemaVersion:2,id:'pond',objects:[{asset:'Builtin/BW_water'}]}));
 await deleteAsset(root,'/Builtin/Shallow water',{},message=>messages.push(message));
 assert.ok(messages.some(message=>message.includes('worlds using this asset: 1')));
 await deleteAsset(root,'/Builtin/Shallow water',{apply:true,confirm:count=>{assert.equal(count,1);return true;}},()=>{});
 assert.deepEqual(await readHiddenAssets(root),['Builtin/BW_water','Forest/cloud','Forest/local']);
 await fs.access(path.join(root,'worlds/pond.json'));
 assert.deepEqual(Object.keys(JSON.parse(await fs.readFile(registry,'utf8'))),['local','cloud']);
});
